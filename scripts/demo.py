#!/usr/bin/env python3
"""One-command offline demo: a throwaway home, four specs, then the console.

The demo never calls the network and never needs a paid key. It prepares a demo
home under `--home`, generates a master key into `<home>/demo.env`, copies the
four bundled no-credential specs into `<home>/specs`, runs each one through the
real CLI and expects the gate-failure witness to exit 1. It then prints the talk
track, the run ids and the console URL, and serves the console unless told not to.

Usage::

    python scripts/demo.py
    python scripts/demo.py --home .demo --port 8000
    python scripts/demo.py --home "$TEMP/evalh-demo" --no-serve
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Sequence

from cryptography.fernet import Fernet

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "src"
BUNDLED_SPECS = REPO / "examples" / "specs"
DEMO_SPECS = (
    "smoke.yaml",
    "stub-pack.yaml",
    "gated.yaml",
    "gated-failing.yaml",
)
EXPECTED_EXITS = {
    "smoke.yaml": 0,
    "stub-pack.yaml": 0,
    "gated.yaml": 0,
    "gated-failing.yaml": 1,
}
DEFAULT_HOME = ".demo"
DEFAULT_PORT = 8000
RUN_LINE = re.compile(r"^run\s+(?P<run_id>\S+)\s+status=(?P<status>\S+)", re.MULTILINE)

TALK_TRACK = """Talk track
  1. Start on the run list: four runs from the offline specs, with status,
     pass rate, cost, duration and the spec graph thumbnail.
  2. Open /specs: the four specs, each with its estimate and a Launch action.
  3. Open stub-pack in the structured form, change a prompt, Save and run.
  4. On /launch show the estimate from observed medians, then launch.
  5. Watch the run fill in on /runs/<id>: heatmap, evidence, gate cards, UTC times.
  6. Open /compare with two runs: deltas, intervals, cost per correct answer.
  7. Open /credentials: BYOK, masked keys; this demo needs no key at all."""


class DemoError(Exception):
    """One demo step failed; the message names the step and the fix."""


def build_parser() -> argparse.ArgumentParser:
    """Build the demo's argument parser."""
    parser = argparse.ArgumentParser(
        description="Run the offline eval-harness demo: a demo home, the four "
        "no-credential specs, the expected exit codes, the talk track and the "
        "console. No network and no paid key.",
    )
    parser.add_argument(
        "--home",
        default=DEFAULT_HOME,
        help=f"demo home directory (default {DEFAULT_HOME})",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=DEFAULT_PORT,
        help=f"console port for the served demo (default {DEFAULT_PORT})",
    )
    parser.add_argument(
        "--no-serve",
        action="store_true",
        help="prepare and run, print the report, and do not start the console",
    )
    parser.add_argument(
        "--no-run",
        action="store_true",
        help="prepare the home and print the talk track, but run no specs",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="delete the demo home first, including its key and database",
    )
    return parser


def base_env(home: Path, master_key: str) -> dict[str, str]:
    """Child environment: repo src on the path, demo home, demo vault key."""
    env = {key: value for key, value in os.environ.items() if not key.startswith("EVALH_")}
    env["PYTHONPATH"] = str(SRC)
    env["EVALH_HOME"] = str(home)
    env["EVALH_SPECS_DIR"] = str(home / "specs")
    env["EVALH_MASTER_KEY"] = master_key
    env["PYTHONUNBUFFERED"] = "1"
    return env


def read_key(path: Path) -> str | None:
    """Read the demo master key from an existing env file, if it has one."""
    if not path.is_file():
        return None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("EVALH_MASTER_KEY="):
            return line.split("=", 1)[1].strip()
    return None


def write_key(path: Path, master_key: str) -> None:
    """Write the demo env file and narrow it to the owner where the OS allows."""
    path.write_text(
        "# Generated by scripts/demo.py for the offline demo vault.\n"
        "# Do not commit this file. It holds the only copy of this demo key.\n"
        f"EVALH_MASTER_KEY={master_key}\n",
        encoding="utf-8",
    )
    try:
        path.chmod(0o600)
    except OSError:  # pragma: no cover - Windows may refuse the mode; key stays local
        pass


def prepare_home(home: Path, *, reset: bool) -> tuple[str, list[Path]]:
    """Create the demo home, key file and specs; return the key and spec paths."""
    if reset and home.exists():
        shutil.rmtree(home)
    home.mkdir(parents=True, exist_ok=True)
    specs_dir = home / "specs"
    specs_dir.mkdir(parents=True, exist_ok=True)
    env_file = home / "demo.env"
    master_key = read_key(env_file)
    if master_key is None:
        master_key = Fernet.generate_key().decode("ascii")
        write_key(env_file, master_key)
    copied: list[Path] = []
    for name in DEMO_SPECS:
        source = BUNDLED_SPECS / name
        if not source.is_file():
            raise DemoError(
                f"bundled spec not found: {source}. Run the demo from a checkout "
                "of the repository, not from an installed wheel."
            )
        target = specs_dir / name
        shutil.copyfile(source, target)
        copied.append(target)
    return master_key, copied


def run_specs(home: Path, env: dict[str, str]) -> list[tuple[str, int, str]]:
    """Run each demo spec through the CLI and assert its expected exit code."""
    results: list[tuple[str, int, str]] = []
    for name in DEMO_SPECS:
        spec = home / "specs" / name
        completed = subprocess.run(
            [sys.executable, "-m", "evalharness", "run", str(spec)],
            cwd=str(REPO),
            env=env,
            capture_output=True,
            text=True,
        )
        expected = EXPECTED_EXITS[name]
        if completed.returncode != expected:
            detail = (completed.stdout + completed.stderr).strip()
            raise DemoError(
                f"{name} exited {completed.returncode}, expected {expected}.\n{detail}"
            )
        match = RUN_LINE.search(completed.stdout)
        if match is None:
            detail = (completed.stdout + completed.stderr).strip()
            raise DemoError(
                f"{name} did not print a run id line; the CLI output changed.\n{detail}"
            )
        results.append((name, expected, match.group("run_id")))
    return results


def print_report(
    home: Path,
    port: int,
    results: list[tuple[str, int, str]],
    *,
    ran: bool,
) -> None:
    """Print the talk track, the run ids and the console URL."""
    url = f"http://127.0.0.1:{port}/"
    print(f"demo: home {home}")
    print(f"demo: wrote {home / 'demo.env'} (the key is not printed)")
    print(f"demo: specs in {home / 'specs'}")
    print()
    print(TALK_TRACK)
    print()
    if not ran:
        print("Runs skipped (--no-run).")
    else:
        print("Runs")
        for name, expected, run_id in results:
            label = f"exit {expected}"
            if expected != 0:
                label += " (expected gate failure)"
            print(f"  {name:<20} {label:<34} run {run_id}")
    print()
    print(f"Console: {url}")


def serve(home: Path, port: int, env: dict[str, str]) -> int:
    """Run the console in the foreground and return its exit code."""
    print(f"demo: serving {home} at http://127.0.0.1:{port}/ (Ctrl-C to stop)")
    return subprocess.call(
        [
            sys.executable,
            "-m",
            "evalharness",
            "serve",
            "--port",
            str(port),
        ],
        cwd=str(REPO),
        env=env,
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Prepare, run, report and optionally serve the demo; return the exit code."""
    args = build_parser().parse_args(argv)
    home = Path(args.home).expanduser().resolve()
    try:
        master_key, _ = prepare_home(home, reset=args.reset)
        env = base_env(home, master_key)
        results = [] if args.no_run else run_specs(home, env)
    except DemoError as error:
        print(f"demo: FAIL: {error}", file=sys.stderr)
        return 1
    print_report(home, args.port, results, ran=not args.no_run)
    if args.no_serve:
        return 0
    return serve(home, args.port, env)


if __name__ == "__main__":  # pragma: no cover - script entry point
    sys.exit(main())
